use bytes::Bytes;
use std::net::{IpAddr, Ipv4Addr, SocketAddr};

use peercast_core::atom::{Atom, AtomBudget};
use peercast_core::channel_id::ChannelId;
use peercast_core::errors::QuitReason;
use peercast_core::host::{Host, HostFlags1};
use peercast_core::id4::ID4;
use peercast_pcp::relay_client::{RelayNetworkProfile, SERVANT_VERSION};
use peercast_pcp::relay_server::{
    RelayServerError, RelayServerEvent, RelayServerPhase, RelayServerStateMachine, MIN_HELO_VERSION,
};

fn sample_server_sid() -> ChannelId {
    ChannelId::from_hex("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa").unwrap()
}

fn sample_client_sid() -> ChannelId {
    ChannelId::from_hex("bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb").unwrap()
}

fn sample_cid() -> ChannelId {
    ChannelId::from_hex("0123456789abcdef0123456789abcdef").unwrap()
}

#[test]
fn test_p18_server_200_accept_path() {
    let server_sid = sample_server_sid();
    let client_sid = sample_client_sid();
    let client_ip = IpAddr::V4(Ipv4Addr::new(192, 168, 1, 100));

    let mut server =
        RelayServerStateMachine::new(server_sid, RelayNetworkProfile::IPv4, Some(client_ip));
    assert_eq!(server.phase(), RelayServerPhase::WaitingRequest);

    // 1. Scripted raw client HTTP GET request (independent wire bytes, not generated by Rust client)
    let raw_request = b"GET /channel/0123456789ABCDEF0123456789ABCDEF HTTP/1.0\r\n\
                        Host: 127.0.0.1:7144\r\n\
                        User-Agent: PeerCast-Scripted-Test/1.0\r\n\
                        x-peercast-pcp: 1\r\n\
                        \r\n";
    let mut req_buf = Bytes::from_static(raw_request);

    let ev1 = server
        .feed_bytes(&mut req_buf)
        .unwrap()
        .expect("RequestReceived");
    assert!(
        matches!(ev1, RelayServerEvent::RequestReceived(ref req) if req.channel_id == sample_cid())
    );
    assert_eq!(server.phase(), RelayServerPhase::WaitingDecision);

    // 2. Server decides to accept relay connection
    let resp_bytes = server.accept().expect("Accept OK");
    let resp_str = String::from_utf8(resp_bytes).unwrap();
    assert!(resp_str.starts_with("HTTP/1.0 200 OK\r\n"));
    assert!(resp_str.contains("Content-Type: application/x-peercast-pcp\r\n"));
    assert_eq!(server.phase(), RelayServerPhase::WaitingHelo200);

    // 3. Scripted raw client helo Atom
    let client_helo = Atom::new_parent(
        ID4::PCP_HELO,
        vec![
            Atom::new_string(ID4::HELO_AGENT, "TestClient/0.9"),
            Atom::new_leaf(
                ID4::HELO_SESSIONID,
                Bytes::copy_from_slice(client_sid.as_bytes()),
            ),
            Atom::new_u32_le(ID4::HELO_VERSION, SERVANT_VERSION),
            Atom::new_u16_le(ID4::HELO_PORT, 7144),
        ],
    );
    let mut helo_buf = client_helo.to_bytes().unwrap();

    let ev2 = server
        .feed_bytes(&mut helo_buf)
        .unwrap()
        .expect("HandshakeCompleted");
    match ev2 {
        RelayServerEvent::HandshakeCompleted {
            outbound_bytes,
            client_session_id,
            client_agent,
            client_port,
        } => {
            assert_eq!(client_session_id, client_sid);
            assert_eq!(client_agent.as_deref(), Some("TestClient/0.9"));
            assert_eq!(client_port, Some(7144));

            // Decode outbound bytes independently: MUST be oleh followed by ok(1)
            let mut out = outbound_bytes;
            let budget = AtomBudget::default();

            // First atom: oleh
            let oleh = Atom::decode(&mut out, &budget).unwrap().expect("oleh");
            assert_eq!(oleh.name(), ID4::PCP_OLEH);
            let mut oleh_sid = None;
            for child in oleh.children().unwrap() {
                if child.name() == ID4::HELO_SESSIONID {
                    oleh_sid = Some(ChannelId::from_bytes(
                        *child.leaf_bytes().unwrap().first_chunk::<16>().unwrap(),
                    ));
                }
            }
            assert_eq!(oleh_sid, Some(server_sid));

            // Second atom: ok(1) (REQ-032 / A08)
            let ok = Atom::decode(&mut out, &budget).unwrap().expect("ok");
            assert_eq!(ok.name(), ID4::PCP_OK);
            assert_eq!(ok.get_u32_le().unwrap(), 1);

            assert!(out.is_empty(), "No extra bytes after ok(1)");
        }
        _ => panic!("Expected HandshakeCompleted"),
    }

    assert_eq!(server.phase(), RelayServerPhase::Streaming);
}

#[test]
fn test_p18_server_503_full_path() {
    let server_sid = sample_server_sid();
    let client_sid = sample_client_sid();
    let cid = sample_cid();

    let mut server = RelayServerStateMachine::new(server_sid, RelayNetworkProfile::IPv4, None);

    // 1. Client sends GET request
    let raw_request = b"GET /channel/0123456789ABCDEF0123456789ABCDEF HTTP/1.0\r\n\
                        Host: 127.0.0.1:7144\r\n\
                        x-peercast-pcp: 1\r\n\
                        \r\n";
    let mut req_buf = Bytes::from_static(raw_request);
    server.feed_bytes(&mut req_buf).unwrap();

    // 2. Server has no relay slots -> reject_full with candidate host
    let cand_sid = ChannelId::from_hex("33333333333333333333333333333333").unwrap();
    let mut cand = Host::new(cand_sid, cid);
    cand.global_endpoint = Some(SocketAddr::new(
        IpAddr::V4(Ipv4Addr::new(203, 0, 113, 10)),
        7144,
    ));
    cand.flags = HostFlags1::RELAY;

    let resp_bytes = server
        .reject_full(vec![cand.clone()])
        .expect("Reject full OK");
    let resp_str = String::from_utf8(resp_bytes).unwrap();
    assert!(resp_str.starts_with("HTTP/1.0 503 Service Unavailable\r\n"));
    assert_eq!(server.phase(), RelayServerPhase::WaitingHelo503);

    // 3. Client sends helo
    let client_helo = Atom::new_parent(
        ID4::PCP_HELO,
        vec![
            Atom::new_string(ID4::HELO_AGENT, "TestClient/0.9"),
            Atom::new_leaf(
                ID4::HELO_SESSIONID,
                Bytes::copy_from_slice(client_sid.as_bytes()),
            ),
            Atom::new_u32_le(ID4::HELO_VERSION, SERVANT_VERSION),
        ],
    );
    let mut helo_buf = client_helo.to_bytes().unwrap();

    let ev2 = server
        .feed_bytes(&mut helo_buf)
        .unwrap()
        .expect("FullHandshakeCompleted");
    match ev2 {
        RelayServerEvent::FullHandshakeCompleted {
            outbound_bytes,
            client_session_id,
        } => {
            assert_eq!(client_session_id, client_sid);

            // Decode outbound bytes: oleh + host + quit(1003) in strict order (REQ-032, REQ-033)
            let mut out = outbound_bytes;
            let budget = AtomBudget::default();

            // 1. oleh
            let oleh = Atom::decode(&mut out, &budget).unwrap().expect("oleh");
            assert_eq!(oleh.name(), ID4::PCP_OLEH);

            // 2. host
            let host_atom = Atom::decode(&mut out, &budget).unwrap().expect("host");
            assert_eq!(host_atom.name(), ID4::PCP_HOST);
            let parsed_host = Host::from_atom(&host_atom).unwrap();
            assert_eq!(parsed_host.session_id, cand_sid);
            assert_eq!(parsed_host.contact_address(), cand.contact_address());

            // 3. quit(1003)
            let quit_atom = Atom::decode(&mut out, &budget).unwrap().expect("quit");
            assert_eq!(quit_atom.name(), ID4::PCP_QUIT);
            assert_eq!(
                quit_atom.get_u32_le().unwrap(),
                QuitReason::UNAVAILABLE.raw()
            );

            assert!(out.is_empty(), "No extra bytes after quit(1003)");
        }
        _ => panic!("Expected FullHandshakeCompleted"),
    }

    assert_eq!(
        server.phase(),
        RelayServerPhase::Terminal(QuitReason::UNAVAILABLE)
    );
}

#[test]
fn test_p18_server_404_not_found_stops_immediately() {
    let server_sid = sample_server_sid();
    let mut server = RelayServerStateMachine::new(server_sid, RelayNetworkProfile::IPv4, None);

    let raw_request = b"GET /channel/0123456789ABCDEF0123456789ABCDEF HTTP/1.0\r\n\r\n";
    let mut req_buf = Bytes::from_static(raw_request);
    server.feed_bytes(&mut req_buf).unwrap();

    let resp_bytes = server.reject_not_found();
    let resp_str = String::from_utf8(resp_bytes).unwrap();
    assert!(resp_str.starts_with("HTTP/1.0 404 Not Found\r\n"));
    assert_eq!(
        server.phase(),
        RelayServerPhase::Terminal(QuitReason::OFF_AIR)
    );

    // Atom decoding is forbidden on 404 path (REQ-032)
    let dummy_atom = Atom::new_u32_le(ID4::PCP_OK, 1);
    let mut dummy_buf = dummy_atom.to_bytes().unwrap();
    let res = server
        .feed_bytes(&mut dummy_buf)
        .unwrap()
        .expect("Terminal quit");
    assert_eq!(res, RelayServerEvent::Quit(QuitReason::OFF_AIR));
}

#[test]
fn test_p18_server_handles_client_quit_or_failure_and_releases_slot() {
    let server_sid = sample_server_sid();
    let mut server = RelayServerStateMachine::new(server_sid, RelayNetworkProfile::IPv4, None);

    let raw_request = b"GET /channel/0123456789ABCDEF0123456789ABCDEF HTTP/1.0\r\n\r\n";
    let mut req_buf = Bytes::from_static(raw_request);
    server.feed_bytes(&mut req_buf).unwrap();

    // Application accepts slot
    server.accept().unwrap();
    assert_eq!(server.phase(), RelayServerPhase::WaitingHelo200);

    // Client aborts with quit(1001) (SKIP) instead of sending helo
    let quit = Atom::new_u32_le(ID4::PCP_QUIT, QuitReason::SKIP.raw());
    let mut quit_buf = quit.to_bytes().unwrap();

    let ev = server
        .feed_bytes(&mut quit_buf)
        .unwrap()
        .expect("Quit event");
    assert_eq!(ev, RelayServerEvent::Quit(QuitReason::SKIP));
    assert_eq!(server.phase(), RelayServerPhase::Terminal(QuitReason::SKIP));
    assert!(
        server.phase().is_terminal(),
        "Slot is freed upon terminal transition"
    );
}

#[test]
fn test_p18_server_rejects_missing_session_id() {
    let server_sid = sample_server_sid();
    let mut server = RelayServerStateMachine::new(server_sid, RelayNetworkProfile::IPv4, None);

    let raw_request = b"GET /channel/0123456789ABCDEF0123456789ABCDEF HTTP/1.0\r\n\r\n";
    let mut req_buf = Bytes::from_static(raw_request);
    server.feed_bytes(&mut req_buf).unwrap();
    server.accept().unwrap();

    // Client sends helo with agent and version, but MISSING session ID
    let incomplete_helo = Atom::new_parent(
        ID4::PCP_HELO,
        vec![
            Atom::new_string(ID4::HELO_AGENT, "BrokenClient/1.0"),
            Atom::new_u32_le(ID4::HELO_VERSION, 1),
        ],
    );
    let mut helo_buf = incomplete_helo.to_bytes().unwrap();

    let res = server.feed_bytes(&mut helo_buf);
    assert_eq!(res, Err(RelayServerError::MissingSessionId));
}

#[test]
fn test_p18_server_streaming_handles_client_quit() {
    let server_sid = sample_server_sid();
    let client_sid = sample_client_sid();
    let mut server = RelayServerStateMachine::new(server_sid, RelayNetworkProfile::IPv4, None);

    let raw_request = b"GET /channel/0123456789ABCDEF0123456789ABCDEF HTTP/1.0\r\n\r\n";
    let mut req_buf = Bytes::from_static(raw_request);
    server.feed_bytes(&mut req_buf).unwrap();
    server.accept().unwrap();

    let client_helo = Atom::new_parent(
        ID4::PCP_HELO,
        vec![
            Atom::new_leaf(
                ID4::HELO_SESSIONID,
                Bytes::copy_from_slice(client_sid.as_bytes()),
            ),
            Atom::new_u32_le(ID4::HELO_VERSION, SERVANT_VERSION),
        ],
    );
    let mut helo_buf = client_helo.to_bytes().unwrap();
    server.feed_bytes(&mut helo_buf).unwrap();
    assert_eq!(server.phase(), RelayServerPhase::Streaming);

    // During streaming, client sends quit(1000) (NORMAL)
    let quit = Atom::new_u32_le(ID4::PCP_QUIT, QuitReason::NORMAL.raw());
    let mut quit_buf = quit.to_bytes().unwrap();

    let ev = server
        .feed_bytes(&mut quit_buf)
        .unwrap()
        .expect("Quit event");
    assert_eq!(ev, RelayServerEvent::Quit(QuitReason::NORMAL));
    assert_eq!(
        server.phase(),
        RelayServerPhase::Terminal(QuitReason::NORMAL)
    );
}

#[test]
fn test_p18_server_rejects_old_servant_version() {
    let server_sid = sample_server_sid();
    let client_sid = sample_client_sid();
    let mut server = RelayServerStateMachine::new(server_sid, RelayNetworkProfile::IPv4, None);

    let raw_request = b"GET /channel/0123456789ABCDEF0123456789ABCDEF HTTP/1.0\r\n\r\n";
    let mut req_buf = Bytes::from_static(raw_request);
    server.feed_bytes(&mut req_buf).unwrap();
    server.accept().unwrap();

    // Client sends version < MIN_HELO_VERSION (e.g. MIN_HELO_VERSION - 1)
    let bad_version = MIN_HELO_VERSION - 1;
    let old_client_helo = Atom::new_parent(
        ID4::PCP_HELO,
        vec![
            Atom::new_leaf(
                ID4::HELO_SESSIONID,
                Bytes::copy_from_slice(client_sid.as_bytes()),
            ),
            Atom::new_u32_le(ID4::HELO_VERSION, bad_version),
        ],
    );
    let mut helo_buf = old_client_helo.to_bytes().unwrap();

    let res = server.feed_bytes(&mut helo_buf);
    assert_eq!(res, Err(RelayServerError::BadAgentVersion(bad_version)));
    assert_eq!(
        server.phase(),
        RelayServerPhase::Terminal(QuitReason::BAD_AGENT)
    );
}
